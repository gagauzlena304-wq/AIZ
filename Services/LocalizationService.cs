    {
        private static LocalizationService? _instance;
        public static LocalizationService Instance => _instance ??= new LocalizationService();

        private string _currentLanguage = "en";
        public string CurrentLanguage
        {
            get => _currentLanguage;
            set
            {
                if (_currentLanguage != value)
                {
                    _currentLanguage = value;
                    OnPropertyChanged("Item"); // Updates all indexer bindings
                    OnPropertyChanged(nameof(CurrentLanguage));
                    OnPropertyChanged(nameof(CurrentCulture));
                }
            }
        }

        public CultureInfo CurrentCulture => _currentLanguage switch
        {
            "ru" => new CultureInfo("ru-RU"),
            "es" => new CultureInfo("es-ES"),
            "de" => new CultureInfo("de-DE"),
            "ja" => new CultureInfo("ja-JP"),
            "fr" => new CultureInfo("fr-FR"),
            "pt" => new CultureInfo("pt-BR"),
            "it" => new CultureInfo("it-IT"),
            _ => new CultureInfo("en-US")
        };

        public string this[string key]
        {
            get
            {
                if (_translations.TryGetValue(_currentLanguage, out var langDict) && langDict.TryGetValue(key, out var val))
                    return val;
                
                if (_translations["en"].TryGetValue(key, out var enVal))
                    return enVal;
                
                return key;
            }
        }

        public event PropertyChangedEventHandler? PropertyChanged;
        protected void OnPropertyChanged([CallerMemberName] string? propertyName = null)
        {
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(propertyName));
        }

